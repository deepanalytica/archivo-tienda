const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const { createStoreServer } = require('./server.cjs');
const { chromium } = require('playwright');

(async () => {
  const output = path.join(__dirname, 'output', 'playwright');
  const dataDir = path.join(__dirname, 'output', `qa-data-${crypto.randomUUID()}`);
  await fs.mkdir(output, { recursive: true });
  const server = createStoreServer({ dataDir });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  let browser;
  const results = [];
  const errors = [];
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
    for (const [name, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]]) {
      const context = await browser.newContext({ viewport: { width, height }, reducedMotion: 'reduce', acceptDownloads: true });
      const page = await context.newPage();
      page.on('pageerror', (error) => errors.push(`${name}: ${error.message}`));
      await page.goto(base);
      await page.waitForFunction(() => document.querySelectorAll('.product-card').length === 9);
      await page.evaluate(async () => { for (const img of document.images) img.loading = 'eager'; await Promise.all([...document.images].map((img) => img.decode().catch(() => {}))); });
      const layout = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, broken: [...document.images].filter((img) => !img.naturalWidth).map((img) => img.src) }));
      assert.equal(layout.scrollWidth, width, `${name}: horizontal overflow`); assert.deepEqual(layout.broken, []);
      await page.screenshot({ path: path.join(output, `${name}-hero.png`) });
      await page.screenshot({ path: path.join(output, `${name}-full.png`), fullPage: true });
      await page.locator('.brand-filters [data-filter-brand="neblina"]').click();
      assert.equal(await page.locator('.product-card').count(), 3);
      await page.locator('#category-filter').selectOption('Polerones');
      assert.equal(await page.locator('.product-card').count(), 1);
      await page.getByRole('searchbox', { name: 'Buscar productos' }).fill('ninguna-coincidencia');
      assert.equal(await page.locator('.product-card').count(), 0);
      await page.getByRole('button', { name: 'Ver toda la selección' }).click();
      assert.equal(await page.locator('.product-card').count(), 9);
      await page.locator('#sort').selectOption('price-asc');
      assert.equal(await page.locator('.product-card').first().getAttribute('data-product'), 'logic-cap');
      await page.locator('[data-save="umbral-tee"]').click();
      await page.getByRole('button', { name: 'Ver favoritos', exact: true }).click();
      assert.equal(await page.locator('.product-card').count(), 1);
      await page.reload();
      assert.equal(await page.locator('#favorite-count').innerText(), '1');
      await page.getByRole('button', { name: 'Ver Polera Desfase de UMBRAL', exact: true }).click();
      await page.getByRole('button', { name: /Agregar a la bolsa/ }).click();
      assert.match(await page.locator('#size-error').innerText(), /Selecciona/);
      await page.getByRole('button', { name: 'Talla M', exact: true }).click();
      await page.getByRole('button', { name: 'Aumentar cantidad', exact: true }).click();
      await page.getByRole('button', { name: 'Campaña', exact: true }).click();
      assert.match(await page.locator('#detail-image').getAttribute('src'), /campaign/);
      await page.getByRole('button', { name: 'Detalles', exact: true }).click();
      assert.match(await page.locator('#detail-image').getAttribute('src'), /detail/);
      await page.getByRole('button', { name: 'Prenda', exact: true }).click();
      await page.screenshot({ path: path.join(output, `${name}-product.png`) });
      await page.getByRole('button', { name: /Agregar a la bolsa/ }).click();
      await page.locator('#cart-dialog[open]').waitFor();
      await page.getByRole('button', { name: 'Aumentar cantidad de Polera Desfase, talla M', exact: true }).click();
      await page.getByRole('button', { name: 'Reducir cantidad de Polera Desfase, talla M', exact: true }).click();
      assert.equal(await page.locator('#cart-count').innerText(), '2');
      await page.getByRole('button', { name: 'Cerrar bolsa', exact: true }).click();
      await page.getByRole('button', { name: 'Ver Gorro Módulo de WE ARE LOGIC', exact: true }).click();
      await page.getByRole('button', { name: /Agregar a la bolsa/ }).click();
      assert.equal(await page.locator('.cart-line').count(), 2);
      await page.reload();
      assert.equal(await page.locator('#cart-count').innerText(), '3');
      await page.getByRole('button', { name: 'Abrir bolsa, 3 productos', exact: true }).click();
      await page.screenshot({ path: path.join(output, `${name}-cart.png`) });
      await page.getByRole('button', { name: /Preparar solicitud/ }).click();
      await page.getByRole('textbox', { name: 'Nombre completo', exact: true }).fill(`Prueba QA ${name}`);
      await page.getByRole('textbox', { name: 'Correo electrónico', exact: true }).fill('qa@example.test');
      await page.getByRole('textbox', { name: 'Ciudad / comuna', exact: true }).fill('Santiago');
      await page.getByRole('textbox', { name: /Algo que debamos saber/ }).fill('Prueba automatizada aislada, no es un pedido real.');
      await page.getByRole('button', { name: /Enviar solicitud sin cobro/ }).click();
      await page.locator('#checkout-success:not([hidden])').waitFor();
      const reference = await page.locator('#success-reference').innerText(); assert.match(reference, /AR-/);
      assert.equal(await page.locator('#cart-count').innerText(), '0');
      const downloadPromise = page.waitForEvent('download');
      await page.getByRole('button', { name: /Descargar resumen/ }).click();
      const download = await downloadPromise; assert.match(download.suggestedFilename(), /^AR-.*\.txt$/);
      const admin = await context.newPage(); await admin.goto(`${base}/admin.html`);
      await admin.locator('.admin-order').first().waitFor();
      const orderResponse = await context.request.get(`${base}/api/orders`);
      const order = (await orderResponse.json()).orders.find((item) => reference.includes(item.id));
      assert.equal(order.subtotal, 66970); assert.equal(order.items.length, 2); assert.equal(order.payment, 'Sin cobro');
      await admin.getByRole('combobox', { name: `Estado de ${order.id}`, exact: true }).selectOption('Contactado');
      await admin.waitForFunction((id) => document.querySelector(`select[aria-label="Estado de ${id}"]`)?.value === 'Contactado' && !document.querySelector(`select[aria-label="Estado de ${id}"]`)?.disabled, order.id);
      await admin.reload(); await admin.locator('.admin-order').first().waitFor();
      assert.equal(await admin.getByRole('combobox', { name: `Estado de ${order.id}`, exact: true }).inputValue(), 'Contactado');
      await admin.screenshot({ path: path.join(output, `${name}-admin.png`), fullPage: true });
      results.push({ viewport: name, layout: 'ok', catalog: 'ok', favorites: 'persisted', cart: 'persisted / mixed brands', checkout: 'stored / no charge', admin: 'state persisted' });
      await context.close();
    }
    const requestKey = crypto.randomUUID();
    const payload = { requestKey, customer: { name: 'Prueba servidor', email: 'qa@example.test', city: 'Santiago' }, items: [{ id: 'neblina-tee', size: 'L', quantity: 1, price: 1 }], subtotal: 1 };
    const send = (input) => fetch(`${base}/api/orders`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input) });
    const [first, duplicate] = await Promise.all([send(payload), send(payload)]);
    const order1 = (await first.json()).order; const order2 = (await duplicate.json()).order;
    assert.equal(order1.id, order2.id); assert.equal(order1.subtotal, 24990);
    const invalid = await send({ ...payload, requestKey: crypto.randomUUID(), items: [{ id: 'neblina-tee', size: 'INVALID', quantity: 1 }] }); assert.equal(invalid.status, 400);
    const badQty = await send({ ...payload, requestKey: crypto.randomUUID(), items: [{ id: 'neblina-tee', size: 'L', quantity: 11 }] }); assert.equal(badQty.status, 400);
    const privateFile = await fetch(`${base}/data/orders.json`); assert.equal(privateFile.status, 404);
    assert.deepEqual(errors, []);
    const report = { results, serverChecks: ['recalculates prices', 'concurrent retry is idempotent', 'rejects invalid size and quantity', 'private order file not served'], errors };
    await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
  } finally { if (browser) await browser.close(); await new Promise((resolve) => server.close(resolve)); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
